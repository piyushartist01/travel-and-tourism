/*DESTINATION PAGE */

if (window.location.pathname.includes("destination.html")) {

    document.querySelectorAll(".card").forEach(function (card) {

        card.addEventListener("click", function (event) {

            if (event.target.closest(".wishlist-btn")) {
                return;
            }

            let heading = card.querySelector("h3");

            if (!heading) {
                return;
            }

            let place = heading.textContent.trim().toLowerCase();

            window.location.href =
                "p.html?place=" + encodeURIComponent(place);

        });

    });

}


/*PACKAGE PAGE*/

if (window.location.pathname.includes("p.html")) {

    let place = new URLSearchParams(window.location.search).get("place");

    if (place) {

        place = decodeURIComponent(place).toLowerCase();

        let data = destinations[place];

        if (data) {

            /* HERO */

            document.querySelector(".package-hero img").src =
                data.hero;

            document.querySelector(".package-hero h1").textContent =
                data.title;

            let heroParagraph =
                document.querySelectorAll(".package-hero > p");

            heroParagraph[0].innerHTML = '<i class="fa-solid fa-location-dot"></i> ' + data.location;

            document.querySelector(".package-hero .tagline")
                .textContent = data.tagline;


            /* CARD 1 */

            let cards =
                document.querySelectorAll(".cards-container .card");

            cards[0].querySelector(".card-img img").src =
                data.cards[0].image;

            cards[0].querySelector(".card-content h2")
                .textContent = data.cards[0].title;

            cards[0].querySelector(".card-content p")
                .textContent = data.cards[0].text;


            /* CARD 2 */

            cards[1].querySelector(".card-img img").src =
                data.cards[1].image;

            cards[1].querySelector(".card-content h2")
                .textContent = data.cards[1].title;

            cards[1].querySelector(".card-content p")
                .textContent = data.cards[1].text;


            /* CARD 3 */

            cards[2].querySelector(".card-img img").src =
                data.cards[2].image;

            cards[2].querySelector(".card-content h2")
                .textContent = data.cards[2].title;

            cards[2].querySelector(".card-content p")
                .textContent = data.cards[2].text;

        }

    }

}
let yesBtn = document.getElementById("yesBtn");

if (yesBtn) {
    yesBtn.addEventListener("click", function () {

        let date = document.getElementById("journeyDate").value;
        let duration = document.getElementById("duration").value;
        let travellers = document.getElementById("travellers").value;

        if (!date || !duration || !travellers) {
            alert("Please select trip details.");
            return;
        }

        let packageName = document.querySelector(".package-hero h1").textContent;

        document.getElementById("tripDuration").textContent =
            "Date: " + date + " | Duration: " + duration;

        document.getElementById("tripTravellers").textContent =
            "Travellers: " + travellers;

        document.getElementById("tripPackage").textContent =
            "Package: " + packageName;

        alert("Your seat has been booked!");
    });
}